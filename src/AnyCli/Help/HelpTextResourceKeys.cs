namespace AnyCli.Help;

/// <summary>
/// Defines the resource keys used by the built-in help text resources.
/// </summary>
public static class HelpTextResourceKeys
{
    /// <summary>
    /// The usage section heading.
    /// </summary>
    public const string Usage = nameof(Usage);

    /// <summary>
    /// The description section heading.
    /// </summary>
    public const string Description = nameof(Description);

    /// <summary>
    /// The commands section heading.
    /// </summary>
    public const string Commands = nameof(Commands);

    /// <summary>
    /// The arguments section heading.
    /// </summary>
    public const string Arguments = nameof(Arguments);

    /// <summary>
    /// The options section heading.
    /// </summary>
    public const string Options = nameof(Options);

    /// <summary>
    /// The options placeholder in usage syntax.
    /// </summary>
    public const string OptionsPlaceholder = nameof(OptionsPlaceholder);

    /// <summary>
    /// The command placeholder in usage syntax.
    /// </summary>
    public const string CommandPlaceholder = nameof(CommandPlaceholder);

    /// <summary>
    /// The built-in help option description.
    /// </summary>
    public const string HelpOptionDescription = nameof(HelpOptionDescription);

    /// <summary>
    /// The built-in version option description.
    /// </summary>
    public const string VersionOptionDescription = nameof(VersionOptionDescription);

    /// <summary>
    /// The label used before a parameter's default value.
    /// </summary>
    public const string DefaultValue = nameof(DefaultValue);
}
